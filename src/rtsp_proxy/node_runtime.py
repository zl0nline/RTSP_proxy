class NodeSupervisorError(RuntimeError):
    """A scoped media-node lifecycle operation failed closed."""


class LinuxNodeSupervisor:
    """Own config, exact process operation, identity and smoke as one module."""

    def __init__(
        self,
        *,
        config_store: SecureNodeConfigStore,
        process: NodeProcessController,
        smoke: NodeSmokeProbe,
        port_is_bindable: Callable[[int], bool],
        smoke_attempts: int = 1,
        retry_delay_seconds: float = 0,
        sleep: Callable[[float], None] = time.sleep,
    ) -> None:
        if smoke_attempts < 1 or smoke_attempts > 120:
            raise ValueError("node_smoke_attempts_invalid")
        if retry_delay_seconds < 0 or retry_delay_seconds > 5:
            raise ValueError("node_smoke_retry_delay_invalid")
        self._config_store = config_store
        self._process = process
        self._smoke = smoke
        self._port_is_bindable = port_is_bindable
        self._smoke_attempts = smoke_attempts
        self._retry_delay_seconds = retry_delay_seconds
        self._sleep = sleep

    def execute(self, command: NodeRuntimeCommand) -> NodeRuntimeObservation:
        from rtsp_proxy.nodes import NodeHealth, NodeRuntimeObservation, NodeState

        expected = MediaNodeConfigRenderer().render(command.spec)
        if command.action is NodeRuntimeAction.PROVISION_START:
            if command.config != expected:
                raise NodeSupervisorError("node_rendered_config_mismatch")
            self._config_store.install(command.spec, expected)

        installed_sha256 = self._config_store.digest(command.spec)
        if command.action is not NodeRuntimeAction.STOP and installed_sha256 != expected.sha256:
            raise NodeSupervisorError("node_config_not_applied")

        snapshot = self._process.execute(command.action, command.spec)
        if command.action is NodeRuntimeAction.STOP:
            if snapshot.active:
                raise NodeSupervisorError("node_process_still_active")
            ports = (
                command.spec.external_port,
                command.spec.api_port,
                command.spec.metrics_port,
            )
            if not all(self._port_is_bindable(port) for port in ports):
                raise NodeSupervisorError("node_listener_still_active")
            return NodeRuntimeObservation(
                state=NodeState.STOPPED,
                health=NodeHealth.UNKNOWN,
                config_compatible=installed_sha256 == expected.sha256,
                applied_revision=(
                    command.spec.desired_revision
                    if installed_sha256 == expected.sha256
                    else 0
                ),
                config_sha256=installed_sha256,
                release_id=command.spec.release_id,
            )

        try:
            if not snapshot.active:
                raise NodeSupervisorError("node_process_not_active")
            if snapshot.executable_sha256 != command.spec.mediamtx_binary_sha256:
                raise NodeSupervisorError("node_process_release_mismatch")
            self._run_smoke(command.spec)
        except NodeSupervisorError:
            try:
                self._process.execute(NodeRuntimeAction.STOP, command.spec)
            except Exception as cleanup_error:
                raise NodeSupervisorError("node_start_failed_cleanup_failed") from cleanup_error
            raise
        return NodeRuntimeObservation(
            state=NodeState.RUNNING,
            health=NodeHealth.HEALTHY,
            management_fresh=True,
            config_compatible=True,
            applied_revision=command.spec.desired_revision,
            process_id=snapshot.pid,
            process_start_ticks=snapshot.process_start_ticks,
            process_boot_id=snapshot.boot_id,
            config_sha256=installed_sha256,
            release_id=command.spec.release_id,
        )

    def _run_smoke(self, spec: NodeRuntimeSpec) -> None:
        last_error: NodeSupervisorError | None = None
        for attempt in range(self._smoke_attempts):
            try:
                self._smoke.check(spec)
                return
            except NodeSupervisorError as error:
                last_error = error
                if attempt + 1 < self._smoke_attempts:
                    self._sleep(self._retry_delay_seconds)
        assert last_error is not None
        raise last_error


class MediaNodeSmokeProbe:
    """Prove exact API, metrics and ordinary RTSP/TCP listeners."""

    def __init__(self, *, timeout_seconds: float) -> None:
        if timeout_seconds <= 0 or timeout_seconds > 10:
            raise ValueError("node_smoke_timeout_invalid")
        self._timeout_seconds = timeout_seconds

    def check(self, spec: NodeRuntimeSpec) -> None:
        config = self._read_http(
            f"http://127.0.0.1:{spec.api_port}/v3/config/global/get",
            "node_api_smoke_failed",
        )
        try:
            actual = json.loads(config)
        except (UnicodeError, json.JSONDecodeError) as error:
            raise NodeSupervisorError("node_api_smoke_failed") from error
        if not isinstance(actual, dict) or not self._global_config_matches(actual, spec):
            raise NodeSupervisorError("node_api_config_mismatch")
        self._read_http(
            f"http://127.0.0.1:{spec.metrics_port}/metrics",
            "node_metrics_smoke_failed",
        )
        self._check_rtsp(spec.external_port)

    def _read_http(self, url: str, error_code: str) -> str:
        request = urllib.request.Request(url, method="GET")
        try:
            with urllib.request.urlopen(request, timeout=self._timeout_seconds) as response:
                content = bytes(response.read(1024 * 1024 + 1))
        except (OSError, urllib.error.HTTPError, urllib.error.URLError) as error:
            raise NodeSupervisorError(error_code) from error
        if len(content) > 1024 * 1024:
            raise NodeSupervisorError(error_code)
        try:
            return content.decode("utf-8")
        except UnicodeError as error:
            raise NodeSupervisorError(error_code) from error

    @staticmethod
    def _global_config_matches(actual: dict[str, object], spec: NodeRuntimeSpec) -> bool:
        return (
            actual.get("api") is True
            and actual.get("apiAddress") == f"127.0.0.1:{spec.api_port}"
            and actual.get("metrics") is True
            and actual.get("metricsAddress") == f"127.0.0.1:{spec.metrics_port}"
            and actual.get("rtsp") is True
            and actual.get("rtspAddress") == f":{spec.external_port}"
            and actual.get("rtspTransports") == ["tcp"]
            and actual.get("rtspEncryption") == "no"
            and actual.get("rtmp") is False
            and actual.get("hls") is False
            and actual.get("webrtc") is False
            and actual.get("srt") is False
        )

    def _check_rtsp(self, port: int) -> None:
        request = (
            f"OPTIONS rtsp://127.0.0.1:{port}/ RTSP/1.0\r\n"
            "CSeq: 1\r\n"
            "User-Agent: rtsp-proxy-node-smoke/1\r\n\r\n"
        ).encode("ascii")
        try:
            with socket.create_connection(
                ("127.0.0.1", port),
                timeout=self._timeout_seconds,
            ) as connection:
                connection.settimeout(self._timeout_seconds)
                connection.sendall(request)
                response = bytearray()
                while b"\r\n\r\n" not in response:
                    chunk = connection.recv(4096)
                    if not chunk:
                        break
                    response.extend(chunk)
                    if len(response) > 8192:
                        raise NodeSupervisorError("node_rtsp_smoke_failed")
        except (OSError, TimeoutError) as error:
            raise NodeSupervisorError("node_rtsp_smoke_failed") from error
        first_line = bytes(response).partition(b"\r\n")[0].split()
        if (
            len(first_line) < 2
            or first_line[0] != b"RTSP/1.0"
            or len(first_line[1]) != 3
            or not first_line[1].isdigit()
        ):
            raise NodeSupervisorError("node_rtsp_smoke_failed")


CommandRunner = Callable[[tuple[str, ...]], CompletedProcess[str]]
ProcessIdentityReader = Callable[[Path, int], NodeProcessSnapshot]


class SystemdNodeProcessController:
    """Translate a validated UUID spec into one exact systemd instance operation."""

    def __init__(
        self,
        *,
        systemctl: Path,
        run: CommandRunner | None = None,
        proc_root: Path = Path("/proc"),
    ) -> None:
        if not systemctl.is_absolute():
            raise ValueError("systemctl_path_must_be_absolute")
        self._systemctl = systemctl
        self._run = run or self._run_command
        self._proc_root = proc_root

    def execute(
        self,
        action: NodeRuntimeAction,
        spec: NodeRuntimeSpec,
    ) -> NodeProcessSnapshot:
        unit = f"rtsp-proxy-media@{spec.node_id}.service"
        verbs = {
            NodeRuntimeAction.PROVISION_START: "start",
            NodeRuntimeAction.START: "start",
            NodeRuntimeAction.STOP: "stop",
            NodeRuntimeAction.RESTART: "restart",
        }
        if action in verbs:
            self._checked_run(
                (
                    str(self._systemctl),
                    "--no-ask-password",
                    verbs[action],
                    unit,
                )
            )
        result = self._checked_run(
            (
                str(self._systemctl),
                "--no-pager",
                "show",
                unit,
                "--property=ActiveState",
                "--property=MainPID",
            )
        )
        properties = self._parse_properties(result.stdout)
        active_state = properties.get("ActiveState")
        raw_pid = properties.get("MainPID")
        if (
            active_state is None
            or raw_pid is None
            or not raw_pid.isascii()
            or not raw_pid.isdigit()
        ):
            raise NodeSupervisorError("systemd_node_status_invalid")
        pid = int(raw_pid)
        if active_state != "active":
            if pid != 0:
                raise NodeSupervisorError("systemd_inactive_node_has_pid")
            return NodeProcessSnapshot(
                active=False,
                pid=None,
                process_start_ticks=None,
                boot_id=None,
                executable_sha256=None,
            )
        if pid < 1:
            raise NodeSupervisorError("systemd_active_node_missing_pid")
        return self._read_process_identity(pid)

    def _checked_run(self, arguments: tuple[str, ...]) -> CompletedProcess[str]:
        try:
            result = self._run(arguments)
        except (OSError, subprocess.TimeoutExpired) as error:
            raise NodeSupervisorError("systemd_node_command_failed") from error
        if result.returncode != 0:
            raise NodeSupervisorError("systemd_node_command_failed")
        return result

    @staticmethod
    def _run_command(arguments: tuple[str, ...]) -> CompletedProcess[str]:
        return subprocess.run(
            arguments,
            check=False,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=30,
            env={"LC_ALL": "C", "PATH": os.defpath},
        )

    @staticmethod
    def _parse_properties(output: str) -> dict[str, str]:
        properties: dict[str, str] = {}
        for line in output.splitlines():
            key, separator, value = line.partition("=")
            if not separator or not key or key in properties:
                raise NodeSupervisorError("systemd_node_status_invalid")
            properties[key] = value
        return properties

    def _read_process_identity(self, pid: int) -> NodeProcessSnapshot:
        return _read_linux_process_identity(self._proc_root, pid)


class DirectNodeProcessController:
    """Native contract adapter: independent MediaMTX processes without systemd."""

    def __init__(
        self,
        *,
        mediamtx_binary: Path,
        config_root: Path,
        proc_root: Path = Path("/proc"),
        process_identity: ProcessIdentityReader | None = None,
    ) -> None:
        if not mediamtx_binary.is_absolute() or not mediamtx_binary.is_file():
            raise ValueError("mediamtx_binary_invalid")
        if not config_root.is_absolute():
            raise ValueError("node_config_root_must_be_absolute")
        self._mediamtx_binary = mediamtx_binary
        self._config_root = config_root
        self._proc_root = proc_root
        self._process_identity = process_identity or _read_linux_process_identity
        self._processes: dict[UUID, subprocess.Popen[bytes]] = {}

    def execute(
        self,
        action: NodeRuntimeAction,
        spec: NodeRuntimeSpec,
    ) -> NodeProcessSnapshot:
        if action is NodeRuntimeAction.STOP:
            self._stop(spec.node_id)
            return self._inactive_snapshot()
        if action is NodeRuntimeAction.RESTART:
            self._stop(spec.node_id)
            self._start(spec)
        elif action in {NodeRuntimeAction.PROVISION_START, NodeRuntimeAction.START}:
            process = self._processes.get(spec.node_id)
            if process is None or process.poll() is not None:
                self._start(spec)
        process = self._processes.get(spec.node_id)
        if process is None or process.poll() is not None:
            return self._inactive_snapshot()
        return self._process_identity(self._proc_root, process.pid)

    def close(self) -> None:
        for node_id in tuple(self._processes):
            self._stop(node_id)

    def _start(self, spec: NodeRuntimeSpec) -> None:
        config = self._config_root / str(spec.node_id) / "mediamtx.yml"
        if not config.is_file() or config.is_symlink():
            raise NodeSupervisorError("node_config_not_applied")
        try:
            process = subprocess.Popen(
                (str(self._mediamtx_binary), str(config)),
                stdin=subprocess.DEVNULL,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                close_fds=True,
                start_new_session=True,
                env={"LC_ALL": "C", "PATH": os.defpath},
            )
        except OSError as error:
            raise NodeSupervisorError("node_process_start_failed") from error
        self._processes[spec.node_id] = process

    def _stop(self, node_id: UUID) -> None:
        process = self._processes.pop(node_id, None)
        if process is None or process.poll() is not None:
            return
        process.terminate()
        try:
            process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            process.kill()
            try:
                process.wait(timeout=5)
            except subprocess.TimeoutExpired as error:
                raise NodeSupervisorError("node_process_stop_failed") from error

    @staticmethod
    def _inactive_snapshot() -> NodeProcessSnapshot:
        return NodeProcessSnapshot(
            active=False,
            pid=None,
            process_start_ticks=None,
            boot_id=None,
            executable_sha256=None,
        )


def _read_linux_process_identity(proc_root: Path, pid: int) -> NodeProcessSnapshot:
    process_root = proc_root / str(pid)
    try:
        stat_line = (process_root / "stat").read_text(encoding="ascii")
        closing_parenthesis = stat_line.rfind(")")
        fields = stat_line[closing_parenthesis + 2 :].split()
        if closing_parenthesis < 1 or len(fields) <= 19:
            raise ValueError
        process_start_ticks = int(fields[19])
        boot_id = UUID(
            (proc_root / "sys/kernel/random/boot_id").read_text(encoding="ascii").strip()
        )
        executable = (process_root / "exe").resolve(strict=True)
        digest = hashlib.sha256()
        with executable.open("rb") as binary:
            for chunk in iter(lambda: binary.read(1024 * 1024), b""):
                digest.update(chunk)
    except (OSError, UnicodeError, ValueError) as error:
        raise NodeSupervisorError("node_process_identity_unavailable") from error
    return NodeProcessSnapshot(
        active=True,
        pid=pid,
        process_start_ticks=process_start_ticks,
        boot_id=boot_id,
        executable_sha256=digest.hexdigest(),
    )


