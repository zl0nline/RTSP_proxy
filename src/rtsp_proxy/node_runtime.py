class UnixNodeRuntimeClient:
    """Control-plane adapter for the root-owned, UUID-scoped local helper."""

    def __init__(self, *, socket_path: Path, timeout_seconds: float) -> None:
        if not socket_path.is_absolute():
            raise ValueError("node_runtime_socket_must_be_absolute")
        if timeout_seconds <= 0 or timeout_seconds > 60:
            raise ValueError("node_runtime_timeout_invalid")
        self._socket_path = socket_path
        self._timeout_seconds = timeout_seconds

    def execute(
        self,
        action: NodeRuntimeAction,
        node: MediaNode,
    ) -> NodeRuntimeObservation:
        spec = NodeRuntimeSpec(
            node_id=node.id,
            external_port=node.external_port,
            api_port=node.api_port,
            metrics_port=node.metrics_port,
            desired_revision=node.desired_revision,
            release_id=node.release_id,
            mediamtx_binary_sha256=node.mediamtx_binary_sha256,
        )
        command = NodeRuntimeCommand.for_node(action, spec)
        response_reserve = min(1.0, self._timeout_seconds / 2)
        deadline_unix_ms = int(
            (time.time() + self._timeout_seconds - response_reserve) * 1000
        )
        request = self._encode_command(command, deadline_unix_ms=deadline_unix_ms)
        try:
            with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as connection:
                connection.settimeout(self._timeout_seconds)
                connection.connect(str(self._socket_path))
                connection.sendall(request)
                response = connection.makefile("rb").readline(_MAX_RUNTIME_MESSAGE_BYTES + 1)
        except (OSError, TimeoutError) as error:
            raise NodeSupervisorError("node_runtime_unavailable") from error
        if (
            not response
            or len(response) > _MAX_RUNTIME_MESSAGE_BYTES
            or not response.endswith(b"\n")
        ):
            raise NodeSupervisorError("node_runtime_response_invalid")
        try:
            payload = _RuntimeResponsePayload.model_validate_json(response)
        except ValidationError as error:
            raise NodeSupervisorError("node_runtime_response_invalid") from error
        if payload.schema_version != 1:
            raise NodeSupervisorError("node_runtime_response_invalid")
        if not payload.ok:
            if payload.observation is not None or payload.error is None:
                raise NodeSupervisorError("node_runtime_response_invalid")
            raise NodeSupervisorError(payload.error)
        if payload.observation is None or payload.error is not None:
            raise NodeSupervisorError("node_runtime_response_invalid")
        observation = payload.observation
        return NodeRuntimeObservation(
            state=observation.state,
            health=observation.health,
            management_fresh=observation.management_fresh,
            config_compatible=observation.config_compatible,
            applied_revision=observation.applied_revision,
            process_id=observation.process_id,
            process_start_ticks=observation.process_start_ticks,
            process_boot_id=observation.process_boot_id,
            config_sha256=observation.config_sha256,
            release_id=observation.release_id,
        )

    @staticmethod
    def _encode_command(
        command: NodeRuntimeCommand,
        *,
        deadline_unix_ms: int,
    ) -> bytes:
        payload = {
            "schema_version": 1,
            "action": command.action.value,
            "spec": {
                "node_id": str(command.spec.node_id),
                "external_port": command.spec.external_port,
                "api_port": command.spec.api_port,
                "metrics_port": command.spec.metrics_port,
                "desired_revision": command.spec.desired_revision,
                "release_id": command.spec.release_id,
                "mediamtx_binary_sha256": command.spec.mediamtx_binary_sha256,
            },
            "config": None,
            "deadline_unix_ms": deadline_unix_ms,
        }
        encoded = (json.dumps(payload, separators=(",", ":"), sort_keys=True) + "\n").encode(
            "utf-8"
        )
        if len(encoded) > _MAX_RUNTIME_MESSAGE_BYTES:
            raise NodeSupervisorError("node_runtime_request_too_large")
        return encoded


@dataclass(frozen=True, slots=True)
class NodeRuntimePolicy:
    external_port_start: int
    external_port_end: int
    api_port_start: int
    api_port_end: int
    metrics_port_start: int
    metrics_port_end: int
    release_id: str
    mediamtx_binary_sha256: str
    previous_release_id: str | None = None
    previous_mediamtx_binary_sha256: str | None = None

    def validate(self, spec: NodeRuntimeSpec) -> None:
        if not self.external_port_start <= spec.external_port <= self.external_port_end:
            raise NodeSupervisorError("node_external_port_not_allowed")
        if not self.api_port_start <= spec.api_port <= self.api_port_end:
            raise NodeSupervisorError("node_api_port_not_allowed")
        if not self.metrics_port_start <= spec.metrics_port <= self.metrics_port_end:
            raise NodeSupervisorError("node_metrics_port_not_allowed")
        allowed = {
            (self.release_id, self.mediamtx_binary_sha256),
        }
        if self.previous_release_id is not None:
            if self.previous_mediamtx_binary_sha256 is None:
                raise NodeSupervisorError("node_release_policy_invalid")
            allowed.add(
                (self.previous_release_id, self.previous_mediamtx_binary_sha256)
            )
        if (spec.release_id, spec.mediamtx_binary_sha256) not in allowed:
            raise NodeSupervisorError("node_release_not_allowed")


class _ScopedNodeLock:
    def __init__(
        self,
        *,
        node_id: UUID,
        guard: Lock,
        locks: dict[UUID, tuple[Lock, int]],
    ) -> None:
        self._node_id = node_id
        self._guard = guard
        self._locks = locks
        self._lock: Lock | None = None

    def __enter__(self) -> None:
        with self._guard:
            lock, references = self._locks.get(self._node_id, (Lock(), 0))
            self._locks[self._node_id] = (lock, references + 1)
            self._lock = lock
        lock.acquire()

    def __exit__(self, *exc_info: object) -> None:
        assert self._lock is not None
        self._lock.release()
        with self._guard:
            lock, references = self._locks[self._node_id]
            assert lock is self._lock and references > 0
            if references == 1:
                del self._locks[self._node_id]
            else:
                self._locks[self._node_id] = (lock, references - 1)


class UnixNodeSupervisorServer:
    """Root-side one-request protocol with an allowlisted node policy."""

    def __init__(
        self,
        *,
        supervisor: LinuxNodeSupervisor,
        policy: NodeRuntimePolicy,
        request_timeout_seconds: float = 5,
        operation_timeout_seconds: float = 55,
        cleanup_reserve_seconds: float = 25,
        max_workers: int = 16,
        wall_time: Callable[[], float] = time.time,
        monotonic: Callable[[], float] = time.monotonic,
    ) -> None:
        if request_timeout_seconds <= 0 or request_timeout_seconds > 30:
            raise ValueError("node_runtime_request_timeout_invalid")
        if operation_timeout_seconds <= 0 or operation_timeout_seconds > 55:
            raise ValueError("node_runtime_operation_timeout_invalid")
        if cleanup_reserve_seconds < 20 or cleanup_reserve_seconds >= operation_timeout_seconds:
            raise ValueError("node_runtime_cleanup_reserve_invalid")
        if max_workers < 1 or max_workers > 64:
            raise ValueError("node_runtime_workers_invalid")
        self._supervisor = supervisor
        self._policy = policy
        self._request_timeout_seconds = request_timeout_seconds
        self._operation_timeout_seconds = operation_timeout_seconds
        self._cleanup_reserve_seconds = cleanup_reserve_seconds
        self._max_workers = max_workers
        self._wall_time = wall_time
        self._monotonic = monotonic
        self._node_locks_guard = Lock()
        self._node_locks: dict[UUID, tuple[Lock, int]] = {}

    def serve_connection(self, connection: socket.socket) -> None:
        try:
            connection.settimeout(self._request_timeout_seconds)
            request = connection.makefile("rb").readline(_MAX_RUNTIME_MESSAGE_BYTES + 1)
            command, requested_deadline_unix_ms = self._decode_command(request)
            self._policy.validate(command.spec)
            deadline = self._operation_deadline(requested_deadline_unix_ms)
            with self._node_lock(command.spec.node_id):
                observation = self._supervisor.execute(
                    command,
                    deadline=deadline,
                    cleanup_reserve_seconds=self._cleanup_reserve_seconds,
                )
            payload = self._success_payload(observation)
        except NodeSupervisorError as error:
            payload = self._error_payload(str(error))
        except (OSError, TimeoutError):
            payload = self._error_payload("node_runtime_request_timeout")
        except Exception:
            payload = self._error_payload("node_runtime_internal_error")
        encoded = (json.dumps(payload, separators=(",", ":"), sort_keys=True) + "\n").encode(
            "utf-8"
        )
        with suppress(OSError, TimeoutError):
            connection.sendall(encoded)

    def serve_forever(self, listener: socket.socket) -> None:
        capacity = BoundedSemaphore(self._max_workers)
        with ThreadPoolExecutor(max_workers=self._max_workers) as workers:
            while True:
                capacity.acquire()
                try:
                    connection, _ = listener.accept()
                except BaseException:
                    capacity.release()
                    raise
                workers.submit(self._serve_owned_connection, connection, capacity)

    def _serve_owned_connection(
        self,
        connection: socket.socket,
        capacity: BoundedSemaphore,
    ) -> None:
        try:
            with connection:
                self.serve_connection(connection)
        finally:
            capacity.release()

    def _node_lock(self, node_id: UUID) -> _ScopedNodeLock:
        return _ScopedNodeLock(
            node_id=node_id,
            guard=self._node_locks_guard,
            locks=self._node_locks,
        )

    def _operation_deadline(
        self,
        requested_deadline_unix_ms: int | None,
    ) -> NodeOperationDeadline:
        maximum = self._operation_timeout_seconds
        if requested_deadline_unix_ms is not None:
            requested = requested_deadline_unix_ms / 1000 - self._wall_time()
            if requested <= 0:
                raise NodeSupervisorError("node_runtime_operation_timeout")
            maximum = min(maximum, requested)
        return NodeOperationDeadline(
            expires_monotonic=self._monotonic() + maximum,
            monotonic=self._monotonic,
        )

    @staticmethod
    def _decode_command(
        request: bytes,
    ) -> tuple[NodeRuntimeCommand, int | None]:
        if not request or len(request) > _MAX_RUNTIME_MESSAGE_BYTES or not request.endswith(b"\n"):
            raise NodeSupervisorError("node_runtime_request_invalid")
        try:
            payload = _RuntimeRequestPayload.model_validate_json(request)
        except ValidationError as error:
            raise NodeSupervisorError("node_runtime_request_invalid") from error
        if payload.schema_version != 1:
            raise NodeSupervisorError("node_runtime_request_invalid")
        try:
            spec = NodeRuntimeSpec(
                node_id=payload.spec.node_id,
                external_port=payload.spec.external_port,
                api_port=payload.spec.api_port,
                metrics_port=payload.spec.metrics_port,
                desired_revision=payload.spec.desired_revision,
                release_id=payload.spec.release_id,
                mediamtx_binary_sha256=payload.spec.mediamtx_binary_sha256,
            )
            config = (
                None
                if payload.config is None
                else RenderedNodeConfig(
                    content=payload.config.content,
                    sha256=payload.config.sha256,
                )
            )
            return (
                NodeRuntimeCommand(action=payload.action, spec=spec, config=config),
                payload.deadline_unix_ms,
            )
        except ValueError as error:
            raise NodeSupervisorError("node_runtime_request_invalid") from error

    @staticmethod
    def _success_payload(observation: NodeRuntimeObservation) -> dict[str, object]:
        return {
            "schema_version": 1,
            "ok": True,
            "observation": {
                "state": observation.state.value,
                "health": observation.health.value,
                "management_fresh": observation.management_fresh,
                "config_compatible": observation.config_compatible,
                "applied_revision": observation.applied_revision,
                "process_id": observation.process_id,
                "process_start_ticks": observation.process_start_ticks,
                "process_boot_id": (
                    None
                    if observation.process_boot_id is None
                    else str(observation.process_boot_id)
                ),
                "config_sha256": observation.config_sha256,
                "release_id": observation.release_id,
            },
            "error": None,
        }

    @staticmethod
    def _error_payload(error: str) -> dict[str, object]:
        return {
            "schema_version": 1,
            "ok": False,
            "observation": None,
            "error": error,
        }


class NodeHelperSettings(BaseSettings):
    model_config = SettingsConfigDict(
        env_prefix="RTSP_PROXY_NODE_HELPER_",
        extra="forbid",
        frozen=True,
    )

    config_root: Path = Path("/etc/rtsp-proxy/nodes")
    systemctl: Path = Path("/usr/bin/systemctl")
    mediamtx_binary: Path
    external_port_start: int = Field(ge=1, le=65535)
    external_port_end: int = Field(ge=1, le=65535)
    api_port_start: int = Field(ge=1, le=65535)
    api_port_end: int = Field(ge=1, le=65535)
    metrics_port_start: int = Field(ge=1, le=65535)
    metrics_port_end: int = Field(ge=1, le=65535)
    release_id: str = Field(pattern=r"^[0-9A-Za-z][0-9A-Za-z._-]{0,127}$")
    mediamtx_binary_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    previous_mediamtx_binary: Path | None = None
    previous_release_id: str | None = Field(
        default=None,
        pattern=r"^[0-9A-Za-z][0-9A-Za-z._-]{0,127}$",
    )
    previous_mediamtx_binary_sha256: str | None = Field(
        default=None,
        pattern=r"^[0-9a-f]{64}$",
    )
    smoke_timeout_seconds: float = Field(default=1, gt=0, le=10)
    smoke_attempts: int = Field(default=30, ge=1, le=120)
    smoke_retry_delay_seconds: float = Field(default=0.25, ge=0, le=5)
    request_timeout_seconds: float = Field(default=5, gt=0, le=30)
    operation_timeout_seconds: float = Field(default=55, gt=0, le=55)
    cleanup_reserve_seconds: float = Field(default=25, ge=20, le=30)
    max_workers: int = Field(default=16, ge=1, le=64)

    @model_validator(mode="after")
    def validate_policy(self) -> NodeHelperSettings:
        ranges = (
            (self.external_port_start, self.external_port_end),
            (self.api_port_start, self.api_port_end),
            (self.metrics_port_start, self.metrics_port_end),
        )
        if any(start > end for start, end in ranges):
            raise ValueError("node_helper_port_range_invalid")
        sets = tuple(set(range(start, end + 1)) for start, end in ranges)
        if sets[0] & sets[1] or sets[0] & sets[2] or sets[1] & sets[2]:
            raise ValueError("node_helper_port_ranges_overlap")
        if (
            not self.config_root.is_absolute()
            or not self.systemctl.is_absolute()
            or not self.mediamtx_binary.is_absolute()
        ):
            raise ValueError("node_helper_path_invalid")
        previous = (
            self.previous_mediamtx_binary,
            self.previous_release_id,
            self.previous_mediamtx_binary_sha256,
        )
        if any(value is not None for value in previous) and not all(
            value is not None for value in previous
        ):
            raise ValueError("node_helper_previous_release_incomplete")
        if self.previous_mediamtx_binary is not None:
            if not self.previous_mediamtx_binary.is_absolute():
                raise ValueError("node_helper_path_invalid")
            if self.previous_release_id == self.release_id:
                raise ValueError("node_helper_previous_release_duplicate")
        if self.cleanup_reserve_seconds >= self.operation_timeout_seconds:
            raise ValueError("node_runtime_cleanup_reserve_invalid")
        return self

    def policy(self) -> NodeRuntimePolicy:
        return NodeRuntimePolicy(
            external_port_start=self.external_port_start,
            external_port_end=self.external_port_end,
            api_port_start=self.api_port_start,
            api_port_end=self.api_port_end,
            metrics_port_start=self.metrics_port_start,
            metrics_port_end=self.metrics_port_end,
            release_id=self.release_id,
            mediamtx_binary_sha256=self.mediamtx_binary_sha256,
            previous_release_id=self.previous_release_id,
            previous_mediamtx_binary_sha256=(
                self.previous_mediamtx_binary_sha256
            ),
        )


def run_node_runtime_helper() -> None:
    settings = NodeHelperSettings()  # type: ignore[call-arg]
    listener = _systemd_activation_listener()
    supervisor = LinuxNodeSupervisor(
        config_store=SecureNodeConfigStore(
            root=settings.config_root,
            owner_uid=0,
            binary_catalog={
                (release_id, digest): binary
                for release_id, digest, binary in (
                    (
                        settings.release_id,
                        settings.mediamtx_binary_sha256,
                        settings.mediamtx_binary,
                    ),
                    (
                        settings.previous_release_id,
                        settings.previous_mediamtx_binary_sha256,
                        settings.previous_mediamtx_binary,
                    ),
                )
                if release_id is not None and digest is not None and binary is not None
            },
        ),
        process=SystemdNodeProcessController(systemctl=settings.systemctl),
        smoke=MediaNodeSmokeProbe(timeout_seconds=settings.smoke_timeout_seconds),
        port_is_bindable=_loopback_and_wildcard_port_is_bindable,
        smoke_attempts=settings.smoke_attempts,
        retry_delay_seconds=settings.smoke_retry_delay_seconds,
    )
    UnixNodeSupervisorServer(
        supervisor=supervisor,
        policy=settings.policy(),
        request_timeout_seconds=settings.request_timeout_seconds,
        operation_timeout_seconds=settings.operation_timeout_seconds,
        cleanup_reserve_seconds=settings.cleanup_reserve_seconds,
        max_workers=settings.max_workers,
    ).serve_forever(listener)


def _systemd_activation_listener() -> socket.socket:
    try:
        listen_pid = int(os.environ.get("LISTEN_PID", "0"))
        listen_fds = int(os.environ.get("LISTEN_FDS", "0"))
    except ValueError as error:
        raise SystemExit("node_helper_socket_activation_invalid") from error
    if listen_pid != os.getpid() or listen_fds != 1:
        raise SystemExit("node_helper_socket_activation_invalid")
    try:
        listener = socket.socket(fileno=3)
    except OSError as error:
        raise SystemExit("node_helper_socket_activation_invalid") from error
    if listener.family != socket.AF_UNIX or listener.type & socket.SOCK_STREAM == 0:
        listener.close()
        raise SystemExit("node_helper_socket_activation_invalid")
    return listener


def _loopback_and_wildcard_port_is_bindable(port: int) -> bool:
    probes = (
        (socket.AF_INET, "0.0.0.0"),
        (socket.AF_INET6, "::"),
    )
    for family, address in probes:
        try:
            with socket.socket(family, socket.SOCK_STREAM) as listener:
                listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
                if family is socket.AF_INET6:
                    listener.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_V6ONLY, 1)
                listener.bind((address, port))
        except OSError as error:
            if family is socket.AF_INET6 and error.errno in {
                errno.EAFNOSUPPORT,
                errno.EPROTONOSUPPORT,
                errno.EADDRNOTAVAIL,
            }:
                continue
            return False
    return True
