@dataclass(frozen=True, slots=True)
class NodeRuntimeCommand:
    action: NodeRuntimeAction
    spec: NodeRuntimeSpec
    config: RenderedNodeConfig | None = None

    def __post_init__(self) -> None:
        if self.config is not None:
            raise ValueError("runtime_config_not_allowed")

    @classmethod
    def for_node(
        cls,
        action: NodeRuntimeAction,
        spec: NodeRuntimeSpec,
    ) -> NodeRuntimeCommand:
        return cls(action=action, spec=spec)


class SecureNodeConfigStore:
    """Install one generated config without following node-controlled paths."""

    def __init__(
        self,
        *,
        root: Path,
        owner_uid: int | None = None,
        binary_path: Path | None = None,
        binary_catalog: Mapping[tuple[str, str], Path] | None = None,
    ) -> None:
        if not root.is_absolute():
            raise ValueError("node_config_root_must_be_absolute")
        self._root = root
        self._owner_uid = os.geteuid() if owner_uid is None else owner_uid
        self._binary_path = binary_path
        self._binary_catalog = dict(binary_catalog or {})
        if binary_path is not None and self._binary_catalog:
            raise ValueError("node_binary_catalog_ambiguous")

    def provision(
        self, spec: NodeRuntimeSpec
    ) -> tuple[RenderedNodeConfig, NodeManagementCredentials]:
        credentials = self._new_credentials(spec)
        reader_credentials = self._new_reader_credentials(spec)
        rendered = MediaNodeConfigRenderer().render(spec, credentials, reader_credentials)
        self.install(
            spec,
            rendered,
            credentials=credentials,
            reader_credentials=reader_credentials,
        )
        return rendered, credentials

    def expected(
        self,
        spec: NodeRuntimeSpec,
    ) -> tuple[RenderedNodeConfig, NodeManagementCredentials] | None:
        credentials = self.credentials(spec)
        reader_credentials = self.reader_credentials(spec)
        if credentials is None:
            return None
        return (
            MediaNodeConfigRenderer().render(spec, credentials, reader_credentials),
            credentials,
        )

    def rebind_release(self, spec: NodeRuntimeSpec) -> None:
        if self._binary_path is None and not self._binary_catalog:
            return
        root_fd = self._open_root()
        try:
            node_fd = self._open_node(root_fd, str(spec.node_id))
            try:
                self._install_runtime_environment(node_fd, spec)
            finally:
                os.close(node_fd)
        finally:
            os.close(root_fd)

    def install(
        self,
        spec: NodeRuntimeSpec,
        rendered: RenderedNodeConfig,
        *,
        credentials: NodeManagementCredentials,
        reader_credentials: NodeReaderCredentials | None = None,
    ) -> Path:
        if hashlib.sha256(rendered.content.encode("utf-8")).hexdigest() != rendered.sha256:
            raise ValueError("node_config_digest_mismatch")
        root_fd = self._open_root()
        try:
            node_name = str(spec.node_id)
            with suppress(FileExistsError):
                os.mkdir(node_name, mode=0o700, dir_fd=root_fd)
                os.fsync(root_fd)
            node_fd = self._open_node(root_fd, node_name)
            try:
                self._install_at(node_fd, rendered)
                self._install_credentials(node_fd, credentials)
                if reader_credentials is not None:
                    self._install_reader_credentials(node_fd, reader_credentials)
                self._install_runtime_environment(node_fd, spec)
            finally:
                os.close(node_fd)
        finally:
            os.close(root_fd)
        return self._root / str(spec.node_id) / "mediamtx.yml"

    def digest(self, spec: NodeRuntimeSpec) -> str | None:
        root_fd = self._open_root()
        try:
            try:
                node_fd = self._open_node(root_fd, str(spec.node_id))
            except ValueError:
                return None
            try:
                flags = os.O_RDONLY
                if hasattr(os, "O_CLOEXEC"):
                    flags |= os.O_CLOEXEC
                if hasattr(os, "O_NOFOLLOW"):
                    flags |= os.O_NOFOLLOW
                try:
                    descriptor = os.open("mediamtx.yml", flags, dir_fd=node_fd)
                except FileNotFoundError:
                    return None
                try:
                    file_stat = os.fstat(descriptor)
                    mode = stat.S_IMODE(file_stat.st_mode)
                    if (
                        mode != 0o600
                        or not stat.S_ISREG(file_stat.st_mode)
                        or file_stat.st_uid != self._owner_uid
                    ):
                        raise ValueError("node_config_file_unsafe")
                    digest = hashlib.sha256()
                    while chunk := os.read(descriptor, 1024 * 1024):
                        digest.update(chunk)
                    return digest.hexdigest()
                finally:
                    os.close(descriptor)
            finally:
                os.close(node_fd)
        finally:
            os.close(root_fd)

    def credentials(self, spec: NodeRuntimeSpec) -> NodeManagementCredentials | None:
        root_fd = self._open_root()
        try:
            try:
                node_fd = self._open_node(root_fd, str(spec.node_id))
            except ValueError:
                return None
            try:
                try:
                    payload = self._read_private_file(node_fd, "management.json")
                except FileNotFoundError:
                    return None
                try:
                    raw = json.loads(payload)
                    if not isinstance(raw, dict) or set(raw) != {"username", "password"}:
                        raise ValueError
                    return NodeManagementCredentials(
                        username=str(raw["username"]),
                        password=str(raw["password"]),
                    )
                except (TypeError, ValueError, json.JSONDecodeError) as error:
                    raise ValueError("node_management_credentials_unsafe") from error
            finally:
                os.close(node_fd)
        finally:
            os.close(root_fd)

    def reader_credentials(self, spec: NodeRuntimeSpec) -> NodeReaderCredentials | None:
        root_fd = self._open_root()
        try:
            try:
                node_fd = self._open_node(root_fd, str(spec.node_id))
            except ValueError:
                return None
            try:
                try:
                    payload = self._read_private_file(node_fd, "reader.json")
                except FileNotFoundError:
                    return None
                try:
                    raw = json.loads(payload)
                    if not isinstance(raw, dict) or set(raw) != {"username", "password"}:
                        raise ValueError
                    return NodeReaderCredentials(
                        username=str(raw["username"]),
                        password=str(raw["password"]),
                    )
                except (TypeError, ValueError, json.JSONDecodeError) as error:
                    raise ValueError("node_reader_credentials_unsafe") from error
            finally:
                os.close(node_fd)
        finally:
            os.close(root_fd)

    def _open_root(self) -> int:
        flags = os.O_RDONLY | os.O_DIRECTORY
        if hasattr(os, "O_CLOEXEC"):
            flags |= os.O_CLOEXEC
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        try:
            descriptor = os.open(self._root, flags)
        except OSError as error:
            raise ValueError("node_config_root_unsafe") from error
        root_stat = os.fstat(descriptor)
        mode = stat.S_IMODE(root_stat.st_mode)
        if (
            mode & 0o077
            or not stat.S_ISDIR(root_stat.st_mode)
            or root_stat.st_uid != self._owner_uid
        ):
            os.close(descriptor)
            raise ValueError("node_config_root_unsafe")
        return descriptor

    def _open_node(self, root_fd: int, node_name: str) -> int:
        flags = os.O_RDONLY | os.O_DIRECTORY
        if hasattr(os, "O_CLOEXEC"):
            flags |= os.O_CLOEXEC
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        try:
            descriptor = os.open(node_name, flags, dir_fd=root_fd)
        except OSError as error:
            raise ValueError("node_config_directory_unsafe") from error
        node_stat = os.fstat(descriptor)
        mode = stat.S_IMODE(node_stat.st_mode)
        if (
            mode != 0o700
            or not stat.S_ISDIR(node_stat.st_mode)
            or node_stat.st_uid != self._owner_uid
        ):
            os.close(descriptor)
            raise ValueError("node_config_directory_unsafe")
        return descriptor

    def _install_at(self, node_fd: int, rendered: RenderedNodeConfig) -> None:
        temporary_name = f".mediamtx.{secrets.token_hex(12)}.tmp"
        flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
        if hasattr(os, "O_CLOEXEC"):
            flags |= os.O_CLOEXEC
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        descriptor: int | None = None
        try:
            descriptor = os.open(temporary_name, flags, 0o600, dir_fd=node_fd)
            content = rendered.content.encode("utf-8")
            written = 0
            while written < len(content):
                count = os.write(descriptor, content[written:])
                if count <= 0:
                    raise OSError("short node config write")
                written += count
            os.fchmod(descriptor, 0o600)
            os.fsync(descriptor)
            os.close(descriptor)
            descriptor = None
            os.rename(
                temporary_name,
                "mediamtx.yml",
                src_dir_fd=node_fd,
                dst_dir_fd=node_fd,
            )
            os.fsync(node_fd)
        except Exception:
            if descriptor is not None:
                os.close(descriptor)
            with suppress(FileNotFoundError):
                os.unlink(temporary_name, dir_fd=node_fd)
            raise

    def _install_credentials(
        self,
        node_fd: int,
        credentials: NodeManagementCredentials,
    ) -> None:
        payload = (
            json.dumps(
                {"username": credentials.username, "password": credentials.password},
                separators=(",", ":"),
                sort_keys=True,
            )
            + "\n"
        )
        self._replace_private_file(node_fd, "management.json", payload.encode("utf-8"))

    def _install_reader_credentials(
        self,
        node_fd: int,
        credentials: NodeReaderCredentials,
    ) -> None:
        payload = (
            json.dumps(
                {"username": credentials.username, "password": credentials.password},
                separators=(",", ":"),
                sort_keys=True,
            )
            + "\n"
        )
        self._replace_private_file(node_fd, "reader.json", payload.encode("utf-8"))

    def _install_runtime_environment(self, node_fd: int, spec: NodeRuntimeSpec) -> None:
        binary_path = self._binary_path
        if self._binary_catalog:
            binary_path = self._binary_catalog.get(
                (spec.release_id, spec.mediamtx_binary_sha256)
            )
            if binary_path is None:
                raise ValueError("node_release_not_allowed")
        if binary_path is None:
            return
        digest = _sha256_regular_file(binary_path)
        if digest != spec.mediamtx_binary_sha256:
            raise ValueError("node_binary_digest_mismatch")
        value = str(binary_path)
        if any(character.isspace() or character in "'\"\\" for character in value):
            raise ValueError("node_binary_path_unsafe")
        self._replace_private_file(
            node_fd,
            "runtime.env",
            f"RTSP_PROXY_MEDIAMTX_BINARY={value}\n".encode(),
        )

    def _replace_private_file(self, node_fd: int, name: str, payload: bytes) -> None:
        temporary_name = f".{name}.{secrets.token_hex(12)}.tmp"
        flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
        if hasattr(os, "O_CLOEXEC"):
            flags |= os.O_CLOEXEC
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        descriptor = os.open(temporary_name, flags, 0o600, dir_fd=node_fd)
        try:
            offset = 0
            while offset < len(payload):
                written = os.write(descriptor, payload[offset:])
                if written <= 0:
                    raise OSError("short private file write")
                offset += written
            os.fchmod(descriptor, 0o600)
            os.fsync(descriptor)
        finally:
            os.close(descriptor)
        os.rename(temporary_name, name, src_dir_fd=node_fd, dst_dir_fd=node_fd)
        os.fsync(node_fd)

    def _read_private_file(self, node_fd: int, name: str) -> str:
        flags = os.O_RDONLY
        if hasattr(os, "O_CLOEXEC"):
            flags |= os.O_CLOEXEC
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        descriptor = os.open(name, flags, dir_fd=node_fd)
        try:
            file_stat = os.fstat(descriptor)
            if (
                not stat.S_ISREG(file_stat.st_mode)
                or stat.S_IMODE(file_stat.st_mode) != 0o600
                or file_stat.st_uid != self._owner_uid
                or file_stat.st_size > 4096
            ):
                raise ValueError("node_private_file_unsafe")
            payload = os.read(descriptor, 4097)
            if len(payload) > 4096:
                raise ValueError("node_private_file_unsafe")
            return payload.decode("utf-8")
        finally:
            os.close(descriptor)

    @staticmethod
    def _new_credentials(spec: NodeRuntimeSpec) -> NodeManagementCredentials:
        password = base64.urlsafe_b64encode(secrets.token_bytes(32)).decode("ascii").rstrip("=")
        return NodeManagementCredentials(
            username=f"node-{spec.node_id}",
            password=password,
        )

    @staticmethod
    def _new_reader_credentials(spec: NodeRuntimeSpec) -> NodeReaderCredentials:
        password = base64.urlsafe_b64encode(secrets.token_bytes(32)).decode("ascii").rstrip("=")
        return NodeReaderCredentials(
            username=f"reader-{spec.node_id}",
            password=password,
        )


@dataclass(frozen=True, slots=True)
class NodeProcessSnapshot:
    active: bool
    pid: int | None
    process_start_ticks: int | None
    boot_id: UUID | None
    executable_sha256: str | None

    def __post_init__(self) -> None:
        identity = (
            self.pid,
            self.process_start_ticks,
            self.boot_id,
            self.executable_sha256,
        )
        if self.active:
            if (
                self.pid is None
                or self.pid < 1
                or self.process_start_ticks is None
                or self.process_start_ticks < 1
                or self.boot_id is None
                or self.executable_sha256 is None
            ):
                raise ValueError("active_node_process_identity_incomplete")
        elif any(value is not None for value in identity):
            raise ValueError("inactive_node_process_has_identity")


