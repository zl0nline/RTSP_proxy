@dataclass(frozen=True, slots=True)
class NodeRuntimeCommand:
    action: NodeRuntimeAction
    spec: NodeRuntimeSpec
    config: RenderedNodeConfig | None = None

    def __post_init__(self) -> None:
        if self.action is NodeRuntimeAction.PROVISION_START:
            if self.config is None:
                raise ValueError("runtime_config_required")
        elif self.config is not None:
            raise ValueError("runtime_config_not_allowed")

    @classmethod
    def for_node(
        cls,
        action: NodeRuntimeAction,
        spec: NodeRuntimeSpec,
    ) -> NodeRuntimeCommand:
        config = (
            MediaNodeConfigRenderer().render(spec)
            if action is NodeRuntimeAction.PROVISION_START
            else None
        )
        return cls(action=action, spec=spec, config=config)


class SecureNodeConfigStore:
    """Install one generated config without following node-controlled paths."""

    def __init__(self, *, root: Path, group_id: int | None) -> None:
        if not root.is_absolute():
            raise ValueError("node_config_root_must_be_absolute")
        self._root = root
        self._group_id = group_id

    def install(
        self,
        spec: NodeRuntimeSpec,
        rendered: RenderedNodeConfig,
    ) -> Path:
        if hashlib.sha256(rendered.content.encode("utf-8")).hexdigest() != rendered.sha256:
            raise ValueError("node_config_digest_mismatch")
        root_fd = self._open_root()
        try:
            node_name = str(spec.node_id)
            with suppress(FileExistsError):
                os.mkdir(node_name, mode=0o750, dir_fd=root_fd)
            node_fd = self._open_node(root_fd, node_name)
            try:
                self._install_at(node_fd, rendered)
            finally:
                os.close(node_fd)
        finally:
            os.close(root_fd)
        return self._root / str(spec.node_id) / "mediamtx.yml"

    def digest(self, spec: NodeRuntimeSpec) -> str | None:
        root_fd = self._open_root()
        try:
            try:
                node_fd = self._open_node(root_fd, str(spec.node_id))
            except ValueError:
                return None
            try:
                flags = os.O_RDONLY
                if hasattr(os, "O_CLOEXEC"):
                    flags |= os.O_CLOEXEC
                if hasattr(os, "O_NOFOLLOW"):
                    flags |= os.O_NOFOLLOW
                try:
                    descriptor = os.open("mediamtx.yml", flags, dir_fd=node_fd)
                except FileNotFoundError:
                    return None
                try:
                    mode = stat.S_IMODE(os.fstat(descriptor).st_mode)
                    if mode != 0o640:
                        raise ValueError("node_config_file_unsafe")
                    digest = hashlib.sha256()
                    while chunk := os.read(descriptor, 1024 * 1024):
                        digest.update(chunk)
                    return digest.hexdigest()
                finally:
                    os.close(descriptor)
            finally:
                os.close(node_fd)
        finally:
            os.close(root_fd)

    def _open_root(self) -> int:
        flags = os.O_RDONLY | os.O_DIRECTORY
        if hasattr(os, "O_CLOEXEC"):
            flags |= os.O_CLOEXEC
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        try:
            descriptor = os.open(self._root, flags)
        except OSError as error:
            raise ValueError("node_config_root_unsafe") from error
        mode = stat.S_IMODE(os.fstat(descriptor).st_mode)
        if mode & 0o022:
            os.close(descriptor)
            raise ValueError("node_config_root_unsafe")
        return descriptor

    def _open_node(self, root_fd: int, node_name: str) -> int:
        flags = os.O_RDONLY | os.O_DIRECTORY
        if hasattr(os, "O_CLOEXEC"):
            flags |= os.O_CLOEXEC
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        try:
            descriptor = os.open(node_name, flags, dir_fd=root_fd)
        except OSError as error:
            raise ValueError("node_config_directory_unsafe") from error
        mode = stat.S_IMODE(os.fstat(descriptor).st_mode)
        if mode != 0o750:
            os.close(descriptor)
            raise ValueError("node_config_directory_unsafe")
        if self._group_id is not None:
            os.fchown(descriptor, 0, self._group_id)
        return descriptor

    def _install_at(self, node_fd: int, rendered: RenderedNodeConfig) -> None:
        temporary_name = f".mediamtx.{secrets.token_hex(12)}.tmp"
        flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
        if hasattr(os, "O_CLOEXEC"):
            flags |= os.O_CLOEXEC
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        descriptor: int | None = None
        try:
            descriptor = os.open(temporary_name, flags, 0o640, dir_fd=node_fd)
            content = rendered.content.encode("utf-8")
            written = 0
            while written < len(content):
                count = os.write(descriptor, content[written:])
                if count <= 0:
                    raise OSError("short node config write")
                written += count
            os.fchmod(descriptor, 0o640)
            if self._group_id is not None:
                os.fchown(descriptor, 0, self._group_id)
            os.fsync(descriptor)
            os.close(descriptor)
            descriptor = None
            os.rename(
                temporary_name,
                "mediamtx.yml",
                src_dir_fd=node_fd,
                dst_dir_fd=node_fd,
            )
            os.fsync(node_fd)
        except Exception:
            if descriptor is not None:
                os.close(descriptor)
            with suppress(FileNotFoundError):
                os.unlink(temporary_name, dir_fd=node_fd)
            raise


@dataclass(frozen=True, slots=True)
class NodeProcessSnapshot:
    active: bool
    pid: int | None
    process_start_ticks: int | None
    boot_id: UUID | None
    executable_sha256: str | None

    def __post_init__(self) -> None:
        identity = (
            self.pid,
            self.process_start_ticks,
            self.boot_id,
            self.executable_sha256,
        )
        if self.active:
            if (
                self.pid is None
                or self.pid < 1
                or self.process_start_ticks is None
                or self.process_start_ticks < 1
                or self.boot_id is None
                or self.executable_sha256 is None
            ):
                raise ValueError("active_node_process_identity_incomplete")
        elif any(value is not None for value in identity):
            raise ValueError("inactive_node_process_has_identity")


