class LinuxNodeSupervisor:
    """Own config, exact process operation, identity and smoke as one module."""

    _STOP_CONVERGENCE_ATTEMPTS = 21
    _STOP_CONVERGENCE_DELAY_SECONDS = 0.05

    def __init__(
        self,
        *,
        config_store: SecureNodeConfigStore,
        process: NodeProcessController,
        smoke: NodeSmokeProbe,
        port_is_bindable: Callable[[int], bool],
        smoke_attempts: int = 1,
        retry_delay_seconds: float = 0,
        sleep: Callable[[float], None] = time.sleep,
    ) -> None:
        if smoke_attempts < 1 or smoke_attempts > 120:
            raise ValueError("node_smoke_attempts_invalid")
        if retry_delay_seconds < 0 or retry_delay_seconds > 5:
            raise ValueError("node_smoke_retry_delay_invalid")
        self._config_store = config_store
        self._process = process
        self._smoke = smoke
        self._port_is_bindable = port_is_bindable
        self._smoke_attempts = smoke_attempts
        self._retry_delay_seconds = retry_delay_seconds
        self._sleep = sleep

    def execute(
        self,
        command: NodeRuntimeCommand,
        *,
        deadline: NodeOperationDeadline | None = None,
        cleanup_reserve_seconds: float = 3,
    ) -> NodeRuntimeObservation:
        from rtsp_proxy.nodes import NodeHealth, NodeRuntimeObservation, NodeState

        mutating = command.action in {
            NodeRuntimeAction.PROVISION_START,
            NodeRuntimeAction.START,
            NodeRuntimeAction.RESTART,
        }
        work_deadline = deadline
        if deadline is not None:
            work_deadline = (
                deadline.before(cleanup_reserve_seconds) if mutating else deadline
            )
            work_deadline.remaining_seconds()

        expected: RenderedNodeConfig | None
        credentials: NodeManagementCredentials | None
        if command.action is NodeRuntimeAction.PROVISION_START:
            expected, credentials = self._config_store.provision(command.spec)
        else:
            expected_state = self._config_store.expected(command.spec)
            expected, credentials = (None, None) if expected_state is None else expected_state
            if command.action in {NodeRuntimeAction.START, NodeRuntimeAction.RESTART}:
                self._config_store.rebind_release(command.spec)
        installed_sha256 = self._config_store.digest(command.spec)
        if command.action in {
            NodeRuntimeAction.PROVISION_START,
            NodeRuntimeAction.START,
            NodeRuntimeAction.RESTART,
        } and (
            expected is None or credentials is None or installed_sha256 != expected.sha256
        ):
            raise NodeSupervisorError("node_config_not_applied")

        try:
            if work_deadline is not None:
                work_deadline.remaining_seconds()
            snapshot = self._process.execute(command.action, command.spec, work_deadline)
            if command.action is NodeRuntimeAction.STOP:
                self._require_stopped(command.spec, snapshot, deadline)
                return self._stopped_observation(
                    command.spec,
                    installed_sha256=installed_sha256,
                    expected_sha256=None if expected is None else expected.sha256,
                )
            if command.action is NodeRuntimeAction.OBSERVE and not snapshot.active:
                return self._stopped_observation(
                    command.spec,
                    installed_sha256=installed_sha256,
                    expected_sha256=None if expected is None else expected.sha256,
                )
            if expected is None or credentials is None or installed_sha256 != expected.sha256:
                raise NodeSupervisorError("node_config_not_applied")
            if not snapshot.active:
                raise NodeSupervisorError("node_process_not_active")
            if snapshot.executable_sha256 != command.spec.mediamtx_binary_sha256:
                raise NodeSupervisorError("node_process_release_mismatch")
            assert credentials is not None
            self._run_smoke(command.spec, credentials, work_deadline)
            after_smoke = self._process.execute(
                NodeRuntimeAction.OBSERVE,
                command.spec,
                work_deadline,
            )
            if after_smoke != snapshot:
                raise NodeSupervisorError("node_process_identity_changed")
        except NodeSupervisorError:
            if not mutating:
                raise
            try:
                stopped = self._process.execute(
                    NodeRuntimeAction.STOP,
                    command.spec,
                    deadline,
                )
                self._require_stopped(command.spec, stopped, deadline)
            except Exception as cleanup_error:
                raise NodeSupervisorError("node_start_failed_cleanup_failed") from cleanup_error
            raise
        return NodeRuntimeObservation(
            state=NodeState.RUNNING,
            health=NodeHealth.HEALTHY,
            management_fresh=True,
            config_compatible=True,
            applied_revision=command.spec.desired_revision,
            process_id=snapshot.pid,
            process_start_ticks=snapshot.process_start_ticks,
            process_boot_id=snapshot.boot_id,
            config_sha256=installed_sha256,
            release_id=command.spec.release_id,
        )

    def _require_stopped(
        self,
        spec: NodeRuntimeSpec,
        snapshot: NodeProcessSnapshot,
        deadline: NodeOperationDeadline | None = None,
    ) -> None:
        if snapshot.active:
            raise NodeSupervisorError("node_process_still_active")
        ports = (spec.external_port, spec.api_port, spec.metrics_port)
        for attempt in range(self._STOP_CONVERGENCE_ATTEMPTS):
            available = tuple(self._port_is_bindable(port) for port in ports)
            if all(available):
                return
            if attempt + 1 < self._STOP_CONVERGENCE_ATTEMPTS:
                delay = self._STOP_CONVERGENCE_DELAY_SECONDS
                if deadline is not None:
                    delay = min(delay, deadline.remaining_seconds())
                self._sleep(delay)
        raise NodeSupervisorError("node_listener_still_active")

    @staticmethod
    def _stopped_observation(
        spec: NodeRuntimeSpec,
        *,
        installed_sha256: str | None,
        expected_sha256: str | None,
    ) -> NodeRuntimeObservation:
        compatible = expected_sha256 is not None and installed_sha256 == expected_sha256
        return NodeRuntimeObservation(
            state=NodeState.STOPPED,
            health=NodeHealth.UNKNOWN,
            config_compatible=compatible,
            applied_revision=spec.desired_revision if compatible else 0,
            config_sha256=installed_sha256,
            release_id=spec.release_id,
        )

    def _run_smoke(
        self,
        spec: NodeRuntimeSpec,
        credentials: NodeManagementCredentials,
        deadline: NodeOperationDeadline | None,
    ) -> None:
        last_error: NodeSupervisorError | None = None
        for attempt in range(self._smoke_attempts):
            try:
                self._smoke.check(spec, credentials, deadline)
                return
            except NodeSupervisorError as error:
                last_error = error
                if attempt + 1 < self._smoke_attempts:
                    delay = self._retry_delay_seconds
                    if deadline is not None:
                        delay = min(delay, deadline.remaining_seconds())
                    self._sleep(delay)
        assert last_error is not None
        raise last_error


class MediaNodeSmokeProbe:
    """Prove exact API, metrics and ordinary RTSP/TCP listeners."""

    def __init__(self, *, timeout_seconds: float) -> None:
        if timeout_seconds <= 0 or timeout_seconds > 10:
            raise ValueError("node_smoke_timeout_invalid")
        self._timeout_seconds = timeout_seconds

    def check(
        self,
        spec: NodeRuntimeSpec,
        credentials: NodeManagementCredentials,
        deadline: NodeOperationDeadline | None = None,
    ) -> None:
        config = self._read_http(
            f"http://127.0.0.1:{spec.api_port}/v3/config/global/get",
            "node_api_smoke_failed",
            credentials,
            deadline,
        )
        try:
            actual = json.loads(config)
        except (UnicodeError, json.JSONDecodeError) as error:
            raise NodeSupervisorError("node_api_smoke_failed") from error
        if not isinstance(actual, dict) or not self._global_config_matches(actual, spec):
            raise NodeSupervisorError("node_api_config_mismatch")
        self._read_http(
            f"http://127.0.0.1:{spec.metrics_port}/metrics",
            "node_metrics_smoke_failed",
            credentials,
            deadline,
        )
        self._check_rtsp(spec.external_port, deadline)

    def _read_http(
        self,
        url: str,
        error_code: str,
        credentials: NodeManagementCredentials,
        deadline: NodeOperationDeadline | None,
    ) -> str:
        request = urllib.request.Request(url, method="GET")
        token = base64.b64encode(f"{credentials.username}:{credentials.password}".encode()).decode(
            "ascii"
        )
        request.add_header("Authorization", f"Basic {token}")
        try:
            timeout = self._operation_timeout(deadline)
            with urllib.request.urlopen(request, timeout=timeout) as response:
                content = bytes(response.read(1024 * 1024 + 1))
        except (OSError, urllib.error.HTTPError, urllib.error.URLError) as error:
            raise NodeSupervisorError(error_code) from error
        if len(content) > 1024 * 1024:
            raise NodeSupervisorError(error_code)
        try:
            return content.decode("utf-8")
        except UnicodeError as error:
            raise NodeSupervisorError(error_code) from error

    @staticmethod
    def _global_config_matches(actual: dict[str, object], spec: NodeRuntimeSpec) -> bool:
        return (
            actual.get("api") is True
            and actual.get("apiAddress") == f"127.0.0.1:{spec.api_port}"
            and actual.get("metrics") is True
            and actual.get("metricsAddress") == f"127.0.0.1:{spec.metrics_port}"
            and actual.get("rtsp") is True
            and actual.get("rtspAddress") == f":{spec.external_port}"
            and actual.get("rtspTransports") == ["tcp"]
            and actual.get("rtspEncryption") == "no"
            and actual.get("rtmp") is False
            and actual.get("hls") is False
            and actual.get("webrtc") is False
            and actual.get("srt") is False
        )

    def _check_rtsp(
        self,
        port: int,
        deadline: NodeOperationDeadline | None,
    ) -> None:
        request = (
            f"OPTIONS rtsp://127.0.0.1:{port}/ RTSP/1.0\r\n"
            "CSeq: 1\r\n"
            "User-Agent: rtsp-proxy-node-smoke/1\r\n\r\n"
        ).encode("ascii")
        try:
            with socket.create_connection(
                ("127.0.0.1", port),
                timeout=self._operation_timeout(deadline),
            ) as connection:
                connection.settimeout(self._operation_timeout(deadline))
                connection.sendall(request)
                response = bytearray()
                while b"\r\n\r\n" not in response:
                    chunk = connection.recv(4096)
                    if not chunk:
                        break
                    response.extend(chunk)
                    if len(response) > 8192:
                        raise NodeSupervisorError("node_rtsp_smoke_failed")
        except (OSError, TimeoutError) as error:
            raise NodeSupervisorError("node_rtsp_smoke_failed") from error
        first_line = bytes(response).partition(b"\r\n")[0].split()
        if (
            len(first_line) < 2
            or first_line[0] != b"RTSP/1.0"
            or len(first_line[1]) != 3
            or not first_line[1].isdigit()
        ):
            raise NodeSupervisorError("node_rtsp_smoke_failed")

    def _operation_timeout(self, deadline: NodeOperationDeadline | None) -> float:
        if deadline is None:
            return self._timeout_seconds
        return deadline.remaining_seconds(maximum=self._timeout_seconds)


