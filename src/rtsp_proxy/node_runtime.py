@dataclass(frozen=True, slots=True)
class NodeOperationDeadline:
    """One monotonic end-to-end budget shared by every lifecycle adapter."""

    expires_monotonic: float
    monotonic: Callable[[], float] = time.monotonic

    def remaining_seconds(self, *, maximum: float | None = None) -> float:
        remaining = self.expires_monotonic - self.monotonic()
        if remaining <= 0:
            raise NodeSupervisorError("node_runtime_operation_timeout")
        return remaining if maximum is None else min(remaining, maximum)

    def before(self, seconds: float) -> NodeOperationDeadline:
        if seconds <= 0:
            raise ValueError("node_runtime_deadline_reserve_invalid")
        deadline = NodeOperationDeadline(
            expires_monotonic=self.expires_monotonic - seconds,
            monotonic=self.monotonic,
        )
        deadline.remaining_seconds()
        return deadline


