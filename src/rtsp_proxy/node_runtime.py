@dataclass(frozen=True, slots=True)
class NodeRuntimeSpec:
    node_id: UUID
    external_port: int
    api_port: int
    metrics_port: int
    desired_revision: int
    release_id: str
    mediamtx_binary_sha256: str

    def __post_init__(self) -> None:
        ports = (self.external_port, self.api_port, self.metrics_port)
        if any(port < 1 or port > 65535 for port in ports):
            raise ValueError("node_port_invalid")
        if len(set(ports)) != len(ports):
            raise ValueError("node_ports_not_unique")
        if self.desired_revision < 1:
            raise ValueError("node_desired_revision_invalid")
        if not self.release_id or len(self.release_id) > 128:
            raise ValueError("node_release_id_invalid")
        if len(self.mediamtx_binary_sha256) != 64 or any(
            character not in "0123456789abcdef" for character in self.mediamtx_binary_sha256
        ):
            raise ValueError("node_binary_sha256_invalid")


@dataclass(frozen=True, slots=True)
class RenderedNodeConfig:
    content: str
    sha256: str

    @classmethod
    def from_content(cls, content: str) -> RenderedNodeConfig:
        if not content.endswith("\n"):
            raise ValueError("node_config_final_newline_required")
        return cls(
            content=content,
            sha256=hashlib.sha256(content.encode("utf-8")).hexdigest(),
        )


@dataclass(frozen=True, slots=True)
class NodeManagementCredentials:
    username: str
    password: str

    def __post_init__(self) -> None:
        if (
            not self.username.startswith("node-")
            or len(self.username) > 64
            or len(self.password) < 32
            or len(self.password) > 128
            or any(character.isspace() for character in self.password)
        ):
            raise ValueError("node_management_credentials_invalid")


