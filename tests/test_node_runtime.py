def test_systemd_adapter_can_only_address_the_exact_uuid_instance(tmp_path: Path) -> None:
    calls: list[tuple[str, ...]] = []
    proc_root = tmp_path / "proc"
    proc_root.mkdir()

    def run(arguments: tuple[str, ...]) -> CompletedProcess[str]:
        calls.append(arguments)
        if "show" in arguments:
            return CompletedProcess(
                arguments,
                0,
                "ActiveState=inactive\nMainPID=0\n",
                "",
            )
        return CompletedProcess(arguments, 0, "", "")

    controller = SystemdNodeProcessController(
        systemctl=Path("/usr/bin/systemctl"),
        run=run,
        proc_root=proc_root,
    )

    snapshot = controller.execute(NodeRuntimeAction.STOP, runtime_spec())

    unit = "rtsp-proxy-media@00000000-0000-0000-0000-000000000001.service"
    assert calls == [
        ("/usr/bin/systemctl", "--no-ask-password", "stop", unit),
        (
            "/usr/bin/systemctl",
            "--no-pager",
            "show",
            unit,
            "--property=ActiveState",
            "--property=MainPID",
        ),
    ]
    assert snapshot.active is False


def test_systemd_adapter_binds_active_pid_start_boot_and_binary_identity(
    tmp_path: Path,
) -> None:
    binary = tmp_path / "mediamtx"
    binary.write_bytes(b"verified-binary")
    proc_root = tmp_path / "proc"
    process_root = proc_root / "1234"
