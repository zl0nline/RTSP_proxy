class HealthySmokeProbe:
    def check(
        self,
        spec: NodeRuntimeSpec,
        credentials: NodeManagementCredentials,
        deadline: object | None = None,
    ) -> None:
        assert spec == runtime_spec()
        assert credentials.username.startswith("node-")


class RecordingProcessController:
    def __init__(self) -> None:
        self.commands: list[tuple[NodeRuntimeAction, UUID]] = []

    def execute(
        self,
        action: NodeRuntimeAction,
        spec: NodeRuntimeSpec,
        deadline: object | None = None,
    ) -> NodeProcessSnapshot:
        self.commands.append((action, spec.node_id))
        stopped = action in {NodeRuntimeAction.STOP, NodeRuntimeAction.DELETE}
        return NodeProcessSnapshot(
            active=not stopped,
            pid=None if stopped else 1234,
            process_start_ticks=None if stopped else 5678,
            boot_id=None
            if stopped
            else UUID("10000000-0000-0000-0000-000000000001"),
            executable_sha256=None if stopped else "a" * 64,
        )


class FailingSmokeProbe:
    def check(
        self,
        spec: NodeRuntimeSpec,
        credentials: NodeManagementCredentials,
        deadline: object | None = None,
    ) -> None:
        raise NodeSupervisorError("node_api_smoke_failed")


class InactiveProcessController:
    def __init__(self) -> None:
        self.commands: list[NodeRuntimeAction] = []

    def execute(
        self,
        action: NodeRuntimeAction,
        spec: NodeRuntimeSpec,
        deadline: object | None = None,
    ) -> NodeProcessSnapshot:
        self.commands.append(action)
        return NodeProcessSnapshot(
            active=False,
            pid=None,
            process_start_ticks=None,
            boot_id=None,
            executable_sha256=None,
        )


class IndeterminateStartProcessController(InactiveProcessController):
    def execute(
        self,
        action: NodeRuntimeAction,
        spec: NodeRuntimeSpec,
        deadline: object | None = None,
    ) -> NodeProcessSnapshot:
        self.commands.append(action)
        if action is NodeRuntimeAction.PROVISION_START:
            raise NodeSupervisorError("systemd_node_command_failed")
        return NodeProcessSnapshot(
            active=False,
            pid=None,
            process_start_ticks=None,
            boot_id=None,
            executable_sha256=None,
        )


class EventuallyHealthySmokeProbe:
    def __init__(self) -> None:
        self.calls = 0

    def check(
        self,
        spec: NodeRuntimeSpec,
        credentials: NodeManagementCredentials,
        deadline: object | None = None,
    ) -> None:
        self.calls += 1
        if self.calls == 1:
            raise NodeSupervisorError("node_api_smoke_failed")


