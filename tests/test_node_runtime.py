class HealthySmokeProbe:
    def check(self, spec: NodeRuntimeSpec) -> None:
        assert spec == runtime_spec()


class RecordingProcessController:
    def __init__(self) -> None:
        self.commands: list[tuple[NodeRuntimeAction, UUID]] = []

    def execute(
        self,
        action: NodeRuntimeAction,
        spec: NodeRuntimeSpec,
    ) -> NodeProcessSnapshot:
        self.commands.append((action, spec.node_id))
        return NodeProcessSnapshot(
            active=action is not NodeRuntimeAction.STOP,
            pid=None if action is NodeRuntimeAction.STOP else 1234,
            process_start_ticks=None if action is NodeRuntimeAction.STOP else 5678,
            boot_id=None
            if action is NodeRuntimeAction.STOP
            else UUID("10000000-0000-0000-0000-000000000001"),
            executable_sha256=None
            if action is NodeRuntimeAction.STOP
            else "a" * 64,
        )


class FailingSmokeProbe:
    def check(self, spec: NodeRuntimeSpec) -> None:
        raise NodeSupervisorError("node_api_smoke_failed")


class EventuallyHealthySmokeProbe:
    def __init__(self) -> None:
        self.calls = 0

    def check(self, spec: NodeRuntimeSpec) -> None:
        self.calls += 1
        if self.calls == 1:
            raise NodeSupervisorError("node_api_smoke_failed")


def test_supervisor_provisions_smokes_and_binds_the_applied_identity(tmp_path: Path) -> None:
    root = tmp_path / "nodes"
    root.mkdir(mode=0o750)
    process = RecordingProcessController()
    supervisor = LinuxNodeSupervisor(
        config_store=SecureNodeConfigStore(root=root, group_id=None),
        process=process,
        smoke=HealthySmokeProbe(),
        port_is_bindable=lambda port: False,
    )
    command = NodeRuntimeCommand.for_node(
        NodeRuntimeAction.PROVISION_START,
        runtime_spec(),
    )

    observation = supervisor.execute(command)

    assert process.commands == [(NodeRuntimeAction.PROVISION_START, runtime_spec().node_id)]
    assert observation.state is NodeState.RUNNING
    assert observation.health is NodeHealth.HEALTHY
    assert observation.management_fresh is True
    assert observation.config_compatible is True
    assert observation.applied_revision == 3
    assert observation.process_id == 1234
    assert observation.process_start_ticks == 5678
    assert observation.process_boot_id == UUID("10000000-0000-0000-0000-000000000001")
    assert observation.config_sha256 == command.config.sha256  # type: ignore[union-attr]
    assert observation.release_id == "release-2026.08.12"


