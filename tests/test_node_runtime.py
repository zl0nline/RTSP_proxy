class SmokeHttpHandler(http.server.BaseHTTPRequestHandler):
    global_config: ClassVar[dict[str, object]] = {}

    def do_GET(self) -> None:
        if self.path == "/v3/config/global/get":
            payload = json.dumps(self.global_config).encode()
        elif self.path == "/metrics":
            payload = b"metrics"
        else:
            self.send_error(404)
            return
        self.send_response(200)
        self.send_header("Content-Length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)

    def log_message(self, format: str, *args: object) -> None:
        pass


def test_smoke_probe_checks_api_metrics_and_plain_rtsp_tcp() -> None:
    api = http.server.ThreadingHTTPServer(("127.0.0.1", 0), SmokeHttpHandler)
    metrics = http.server.ThreadingHTTPServer(("127.0.0.1", 0), SmokeHttpHandler)
    rtsp = socket.socket()
    rtsp.bind(("127.0.0.1", 0))
    rtsp.listen(1)
    api_port = int(api.server_address[1])
    metrics_port = int(metrics.server_address[1])
    rtsp_port = int(rtsp.getsockname()[1])
    spec = NodeRuntimeSpec(
        node_id=runtime_spec().node_id,
        external_port=rtsp_port,
        api_port=api_port,
        metrics_port=metrics_port,
        desired_revision=1,
        release_id="release-2026.08.12",
        mediamtx_binary_sha256="a" * 64,
    )
    SmokeHttpHandler.global_config = {
        "api": True,
        "apiAddress": f"127.0.0.1:{api_port}",
        "metrics": True,
        "metricsAddress": f"127.0.0.1:{metrics_port}",
        "rtsp": True,
        "rtspAddress": f":{rtsp_port}",
        "rtspTransports": ["tcp"],
        "rtspEncryption": "no",
        "rtmp": False,
        "hls": False,
        "webrtc": False,
        "srt": False,
    }

    def answer_rtsp() -> None:
        connection, _ = rtsp.accept()
        with connection:
            request = connection.recv(8192)
            assert request.startswith(b"OPTIONS rtsp://")
            assert b"RTSP/1.0" in request
            connection.sendall(b"RTSP/1.0 200 OK\r\nCSeq: 1\r\n\r\n")

    threads = (
        Thread(target=api.serve_forever),
        Thread(target=metrics.serve_forever),
        Thread(target=answer_rtsp),
    )
    for thread in threads:
        thread.start()
    try:
        MediaNodeSmokeProbe(timeout_seconds=1).check(spec)
    finally:
        api.shutdown()
        metrics.shutdown()
        api.server_close()
        metrics.server_close()
        rtsp.close()
        for thread in threads:
            thread.join(timeout=1)


