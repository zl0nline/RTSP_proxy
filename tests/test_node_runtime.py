def test_secure_config_store_pins_release_binary_and_rotates_private_credentials(
    tmp_path: Path,
) -> None:
    root = tmp_path / "nodes-pinned"
    root.mkdir(mode=0o700)
    binary = tmp_path / "release" / "bin" / "mediamtx"
    binary.parent.mkdir(parents=True)
    binary.write_bytes(b"pinned-media-binary")
    spec = NodeRuntimeSpec(
        node_id=runtime_spec().node_id,
        external_port=12001,
        api_port=13001,
        metrics_port=14001,
        desired_revision=1,
        release_id="release-2026.08.12",
        mediamtx_binary_sha256=hashlib.sha256(b"pinned-media-binary").hexdigest(),
    )
    store = SecureNodeConfigStore(root=root, binary_path=binary)

    first_rendered, first_credentials = store.provision(spec)
    second_rendered, second_credentials = store.provision(spec)

    node_root = root / str(spec.node_id)
    assert (node_root / "runtime.env").read_text() == (f"RTSP_PROXY_MEDIAMTX_BINARY={binary}\n")
    assert (node_root / "runtime.env").stat().st_mode & 0o777 == 0o600
    assert (node_root / "management.json").stat().st_mode & 0o777 == 0o600
    assert (node_root / "reader.json").stat().st_mode & 0o777 == 0o600
    assert first_credentials != second_credentials
    assert first_rendered.sha256 != second_rendered.sha256
    assert store.credentials(spec) == second_credentials
    assert store.reader_credentials(spec) is not None


